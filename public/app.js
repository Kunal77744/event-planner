const form = document.getElementById("plan-form");
const out = document.getElementById("result");
const status = document.getElementById("status");
let lastReq = null;
const chat = document.getElementById("chat-form");
const chatLog = document.getElementById("chat-log");
const inr = new Intl.NumberFormat("en-IN");

function el(tag, text, cls) {
  const n = document.createElement(tag);
  if (text !== undefined) n.textContent = text;
  if (cls) n.className = cls;
  return n;
}
function section(title, id) {
  const s = el("section"); s.setAttribute("aria-labelledby", id);
  const h = el("h2", title); h.id = id; s.append(h); return s;
}
function list(items) { const ul = el("ul"); items.forEach(i => ul.append(el("li", i))); return ul; }

function render(p) {
  out.replaceChildren();
  const b = section("Budget", "h-budget");
  if (p.budget.warning) { const w = el("p", p.budget.warning, "warn"); w.setAttribute("role", "alert"); b.append(w); }
  b.append(el("p", `About Rs ${inr.format(p.budget.per_guest)} per guest`));
  const t = el("table");
  t.append(el("caption", "Budget split by category"));
  const head = el("tr"); ["Category", "Share", "Amount (Rs)"].forEach(h => { const c = el("th", h); c.scope = "col"; head.append(c); });
  t.append(head);
  p.budget.items.forEach(i => { const r = el("tr");
    const th = el("th", i.category); th.scope = "row"; r.append(th, el("td", i.percent + "%"), el("td", inr.format(i.amount))); t.append(r); });
  const wrap = el("div", undefined, "scroll"); wrap.append(t); b.append(wrap);

  const tl = section("Timeline", "h-time");
  if (p.timeline.note) { const n = el("p", p.timeline.note, "warn"); n.setAttribute("role", "note"); tl.append(n); }
  const ol = el("ol");
  p.timeline.steps.forEach(s => ol.append(el("li", `${s.due} (${s.days_before} days before): ${s.task}`)));
  tl.append(ol);

  const v = section("Vendor checklist", "h-vend");
  const ul = el("ul", undefined, "checks");
  p.vendors.forEach((x, i) => { const li = el("li"); const cb = el("input"); cb.type = "checkbox"; cb.id = "v" + i;
    const lb = el("label", x); lb.htmlFor = cb.id; li.append(cb, lb); ul.append(li); });
  v.append(ul);

  const s = section("Ideas for you", "h-ideas");
  s.append(list(p.suggestions.ideas));
  if (p.suggestions.tips.length) { s.append(el("h3", "Tips")); s.append(list(p.suggestions.tips)); }
  s.append(el("p", p.suggestions.source === "gemini" ? "Ideas generated by Gemini." : "Ideas from built-in suggestions.", "muted"));

  const pr = el("button", "Print this plan"); pr.type = "button"; pr.onclick = () => window.print();
  out.append(b, tl, v, s, pr);
  out.focus();
}

form.addEventListener("submit", async e => {
  e.preventDefault();
  const d = Object.fromEntries(new FormData(form));
  d.guests = Number(d.guests); d.budget = Number(d.budget);
  status.textContent = "Building your plan...";
  try {
    const r = await fetch("/api/plan", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(d) });
    const data = await r.json();
    if (!r.ok) {
      const msg = Array.isArray(data.detail) ? data.detail.map(x => x.msg).join("; ") : data.detail;
      status.textContent = "Could not build plan: " + msg; return;
    }
    lastReq = d; status.textContent = "Plan ready."; render(data); chat.hidden = false;
  } catch { status.textContent = "Network error. Please try again."; }
});
document.getElementById("event_date").min = new Date(Date.now() + 864e5).toISOString().slice(0, 10);

chat.addEventListener("submit", async e => {
  e.preventDefault();
  const input = document.getElementById("chat-msg");
  chatLog.textContent = "Updating...";
  try {
    const r = await fetch("/api/refine", { method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ plan: lastReq, message: input.value }) });
    const data = await r.json();
    if (!r.ok) { chatLog.textContent = typeof data.detail === "string" ? data.detail : "Could not apply that change."; return; }
    lastReq = data.request; render(data);
    chatLog.textContent = "Updated: " + data.changes.join("; ");
    input.value = "";
  } catch { chatLog.textContent = "Network error. Please try again."; }
});
